// Writes src/products/packs.ts from the Go SDK's embedded seed packs (product/*/packs/*.json),
// so the npm and Go SDKs ship the same data. Run: node scripts/gen-packs.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")
const out = ["// Generated by scripts/gen-packs.mjs from product/*/packs/*.json. Do not edit.", ""]
const entries = []
for (const product of readdirSync(join(root, "product"), { withFileTypes: true })) {
  if (!product.isDirectory()) continue
  let files = []
  try {
    files = readdirSync(join(root, "product", product.name, "packs")).filter((f) => f.endsWith(".json")).sort()
  } catch {
    continue
  }
  for (const f of files) {
    const data = JSON.parse(readFileSync(join(root, "product", product.name, "packs", f), "utf8"))
    const id = `${product.name}_${f.replace(/\.json$/, "")}`.replace(/[^A-Za-z0-9_]/g, "_")
    out.push(`const ${id} = ${JSON.stringify(data)} as const`, "")
    entries.push(`  "${product.name}/${data.key}": ${id},`)
  }
}
out.push("export const PACKS = {", ...entries, "} as const", "")
writeFileSync(join(root, "src", "products", "packs.ts"), out.join("\n"))
console.log("packs:", entries.length)
